def color_file(c):
    lines = ''.join(f'    <color name="{k}">{v}</color>\n' for k, v in c.items())
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_widget.py: widget palette (Material 1). -->\n'
            f'<resources>\n{lines}</resources>\n')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(text)


def shape(kind, inner):
    return f'<shape {A} android:shape="{kind}">{inner}</shape>'


def switch(on):
    track, thumb, grav = ('w_accent_50', 'w_accent', 'end') if on else ('w_sw_track', 'w_sw_thumb', 'start')
    return f'''<layer-list {A}>
    <item android:width="34dp" android:height="14dp" android:gravity="center">
        <shape android:shape="rectangle"><corners android:radius="7dp" /><solid android:color="@color/{track}" /></shape>
    </item>
    <item android:width="20dp" android:height="20dp" android:gravity="{grav}|center_vertical">
        <shape android:shape="oval"><solid android:color="@color/{thumb}" /></shape>
    </item>
</layer-list>'''


