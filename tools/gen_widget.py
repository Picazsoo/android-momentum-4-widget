"""Generates the widget's RemoteViews layouts, palette and drawables.

The three sizes share ids, and the 7-stop slider needs 4 views per stop, so writing the XML by
hand is error-prone. Run from the repo root:  python tools/gen_widget.py
"""
import io
import os

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'main', 'res')
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'


def slider():
    cells = []
    for i in range(7):
        cells.append(f'''
                <FrameLayout android:id="@+id/cell_{i}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1">
                    <LinearLayout android:layout_width="match_parent" android:layout_height="4dp" android:layout_gravity="center_vertical" android:orientation="horizontal">
                        <ImageView android:id="@+id/seg_l_{i}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1" android:scaleType="fitXY" android:src="@drawable/w_seg_none" />
                        <ImageView android:id="@+id/seg_r_{i}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1" android:scaleType="fitXY" android:src="@drawable/w_seg_none" />
                    </LinearLayout>
                    <ImageView android:layout_width="4dp" android:layout_height="4dp" android:layout_gravity="center" android:src="@drawable/w_tick" />
                    <ImageView android:id="@+id/thumb_{i}" android:layout_width="18dp" android:layout_height="18dp" android:layout_gravity="center" android:src="@drawable/w_thumb_anc" android:visibility="gone" />
                </FrameLayout>''')
    return ''.join(cells)


